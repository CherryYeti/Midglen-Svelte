	<p class="text-2xl font-bold">THE MIDGLEN STORY . . . a personal account</p>
	<p>
		The story of Midglen begins with four apprentices of Frank Lloyd Wright. Setting out from
		Taliesin in 1949 to continue their learning-by-doing experience they undertook to design and
		build a residence in the hills behind Redwood City.
	</p>
	<p>
		California became their choice as a location for the first venture in the belief that innovative
		ideas would find acceptance more readily there than, for example, the east coast. After
		rejecting a number of "perfect" sites with building pads in place, the four chose what a realtor
		called an impossible hill-side south of the San Francisco fog belt. The cost for the two steep
		acres exceeded their initial budget at $1500.
	</p>
	<p>
		Setting up a tent above the site as a base for their operations and as a place to live, the four
		intended to design and build using their own version of Wright's concrete texture block designs
		of the 1920s. Six weeks were allotted in that late spring to complete a design inspired by the
		steep site below. As spring became early summer, two partners convinced the others of the
		approach which became the Midglen plan. All applied themselves to turning out a set of working
		drawings, each on a 2x4 piece of plywood with T-squares and triangles.
	</p>
	<p>
		The plan placed the building near the bottom of the south facing ravine and all agreed the
		building should surround a live oak above the access roadway. The tree location determined the
		ideal place for entry in the center, allowing a minimum of circulation area to access the living
		room, kitchen, and bedrooms.
	</p>
	<p>
		A block casting table was set up, and following the experiment developed at Taliesin in
		after-hours in the workshop, the partners created what became the Midglen block - the reveal
		pattern originally intended as the back of the block to conserve materials, became the front
		pattern. (This was further developed to provide blocks with amber glass inserts and openings for
		ventilating use.) As it turned out, some 6000 blocks were cast for the original building. One
		steel-reinforced wood form was used for all the variations required with inserts to provide
		corners, electrical outlets, etc. Two men working steadily could produce up to 150 blocks in one
		day though production varied. With regular cement they were ready for use in about a week; when
		a special block was needed urgently, or when blockmaking fell behind, high early cement was used
		to produce blocks for use within 3 or 4 days.
	</p>
	<p>
		The steep site was hazardous and a local bull-dozer operator was cajoled into the adventure when
		he agreed to plunge down the hill and managed to stop where the building had been laid out.
		Formwork was placed for the concrete cantilevers, and construction moved ahead.
	</p>
	<p>
		The four apprentices carried out all the work themselves except for welding the copper tubing
		which was encased in the reinforced concrete slab for radiant heating, and they contracted a
		roofer. Concrete finishing was accomplished after hiring an experienced finisher for a day to
		"learn the trade."
	</p>
	<p>
		The four became noticeable locally with their long hair and threadbare looks as they labored on
		their dream. When California winter rains overtook them in November, a friendly neighbor offered
		a chicken house and tack room which served as sleeping quarters. A couple of hands were hired at
		minimal wages (for the experience) and finally after eighteen months the finished product was
		featured in the San Francisco press and hundreds of visitors swarmed over the house built by the
		beatnik guys from Taliesin!
	</p>
	<p>
		The partners, Tony Cappucilli, Bill Patrick, Sean O'hare and Chet Wisniewski, returned to their
		homes in Syracuse, New York, and to Ireland as architects and teachers. Patrick stayed on as
		caretaker and to accept any good offer for sale of the project. Finally, he bought out all
		interests and decided to make it the place to raise a family. It was the realization of Wright's
		observation: "A tree cannot pull up its roots to see if it is growing!"
	</p>
	<p>
		Over the years the original Midglen was expanded twice to provide an architect's studio, a
		larger living room, a master bedroom, and a drafting room. The block forms were resurrected and
		the two sons, Akio and Stevan, soon developed their skills in building, from concrete finishing
		to finished cabinetry.
	</p>
	<p>
		Akio became a contractor and Stevan became architect partner at the Midglen Studio. The compound
		expanded so that each has established a family home, all designed in the philosophy of organic
		architecture. Now three generations share the five acres with three grandchildren, two boys and
		a girl, all having the run of the hill from the bottom of the glen to the pool on top. And the
		mothers, Kinuko, Tina, and Karen have come to support this adventure.
	</p>
	<p>
		The family carries on living the organic concepts of the man who inspired it all, Frank Lloyd
		Wright. Another generation comes to understand the empowerment of his ideas.
	</p>
	<p>
		The original venture cost $31,000. The partners counted food and laundry as part of the building
		cost and awarded themselves $5 a week for living expenses. That was in 1949!
	</p>
	<p>William Arthur Patrick, Architect,</p>
	<p>Taliesin Fellow</p>
	<p>Founder of Midglen Studio 1952</p>
